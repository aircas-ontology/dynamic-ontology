/**
 * @description 将船舶标准表十二列映射为资产属性；原图缺少 D 的最大起重能力对应现有 D0096A0000，元数据保留原始标识符。
 * @param row 按原表顺序录入的数据元标准行。
 * @returns 包含完整原始元数据的船舶资产属性。
 */
function mapShipStandardRow(row: ShipStandardRow): AssetModelProperty {
  const [sourceId, name, shortName, description, dataType, representation] = row;
  const id = sourceId === "0096A0000" ? "D0096A0000" : sourceId;
  return {
    id,
    name,
    shortName: shortName === "—" ? "" : shortName,
    apiName: id,
    dataType,
    representation,
    required: false,
    ...(row[7] === "—" ? {} : { unit: row[7] }),
    description,
    metaList: SHIP_METADATA_LABELS.map((label, index) => ({ label, value: row[index] ?? "—" })),
  };
}

