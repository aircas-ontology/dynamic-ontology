/**
 * @description 将航材原表十二列映射为资产属性，保留原始标准信息供展示和接口保存。
 * @param row 航材标准行。
 * @returns 包含完整元数据的资产模型属性。
 */
function mapAviationMaterialStandardRow(row: AviationMaterialStandardRow): AssetModelProperty {
  const [id, name, shortName, description, dataType, representation] = row;
  return {
    id,
    name,
    shortName: shortName === "—" ? "" : shortName,
    apiName: id,
    dataType,
    representation,
    required: false,
    description,
    ...(row[7] === "—" ? {} : { unit: row[7] }),
    metaList: AVIATION_METADATA_LABELS.map((label, index) => ({ label, value: row[index] ?? "—" })),
  };
}

