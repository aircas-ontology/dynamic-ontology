/**
 * @description 将图片中的油品标准行映射为资产属性，同时保留十二列原始元数据供展开查看。
 * @param row 按原表列顺序录入并去重的数据元。
 * @returns 包含完整表格元数据的油品资产属性。
 */
function mapOilStandardRow(row: OilStandardRow): AssetModelProperty {
  const [id, name, shortName, description, dataType, representation] = row;
  return {
    id,
    name,
    shortName: shortName === "—" ? "" : shortName,
    apiName: createAssetPropertyApiName(name, id, shortName === "—" ? "" : shortName),
    dataType,
    representation,
    required: false,
    ...(row[7] === "—" ? {} : { unit: row[7] }),
    description,
    metaList: OIL_METADATA_LABELS.map((label, index) => ({ label, value: row[index] ?? "—" })),
  };
}

/** 油品资产标准属性列表：四个通用数据元及七十五个油品数据元。 */
export const oilAssetStandardProperties: AssetModelProperty[] = ensureUniqueAssetPropertyApiNames(OIL_ASSET_STANDARD_ROWS.map(mapOilStandardRow));
