/**
 * @description 将人员标准原表完整十二列映射为可展示和保存的属性元数据。
 * @param row 人员标准原表行。
 * @returns 资产模型属性。
 */
function mapPersonnelStandardRow(row: PersonnelStandardRow): AssetModelProperty {
  const [id, name, shortName, description, dataType, representation] = row;
  return {
    id,
    name,
    shortName: shortName === "—" ? "" : shortName,
    apiName: createAssetPropertyApiName(name, id, shortName === "—" ? "" : shortName),
    dataType,
    representation,
    required: false,
    description,
    metaList: row.map((value, index) => ({ label: PERSONNEL_METADATA_LABELS[index] ?? "", value })),
  };
}

/** 人员类资产标准属性列表（对齐数据元规范表）。 */
export const personnelAssetStandardProperties: AssetModelProperty[] = ensureUniqueAssetPropertyApiNames(
  PERSONNEL_ASSET_STANDARD_ROWS.map(mapPersonnelStandardRow),
);
