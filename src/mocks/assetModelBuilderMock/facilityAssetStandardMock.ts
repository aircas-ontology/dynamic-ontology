/**
 * @description 将设施标准原表完整十二列映射为可展示和保存的属性元数据。
 * @param row 设施标准原表行。
 * @returns 资产模型属性。
 */
function mapFacilityStandardRow(row: FacilityStandardRow): AssetModelProperty {
  const [id, name, shortName, description, dataType, representation] = row;
  return {
    id,
    name,
    shortName: shortName === "—" ? "" : shortName,
    apiName: id,
    dataType,
    representation,
    required: false,
    description,
    metaList: row.map((value, index) => ({ label: FACILITY_METADATA_LABELS[index] ?? "", value })),
  };
}

/** 设施类资产标准属性列表（对齐数据元规范表）。 */
export const facilityAssetStandardProperties: AssetModelProperty[] = FACILITY_ASSET_STANDARD_ROWS.map(mapFacilityStandardRow);
